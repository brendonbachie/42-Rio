#include "ft_printf.h"

void	ft_putnbr_fd(int n, char c)
{	
	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (n > 0 && c == '+')
		write(1, "+", 1);
	if (n < 0)
	{
		n *= -1;
		write(1, "-", 1);
	}
	if (n >= 10)
		ft_putnbr_fd(n / 10, c);
	write(1, &"0123456789"[n % 10], 1);
}
